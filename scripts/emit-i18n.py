#!/usr/bin/env python3
"""Write the web UI's Simplified Chinese dictionary and the Help documents.

    python3 scripts/emit-i18n.py

Reads ps5/webui/src/i18n/ui_zh.py (UI strings) and the Markdown under docs/.
Writes ps5/webui/src/js/00c-i18n-dict.js and ps5/webui/src/js/11b-docs-zh.js.
"""
import json
import pathlib
import runpy

ROOT = pathlib.Path(__file__).resolve().parents[1]
UI = ROOT / "ps5/webui/src/i18n/ui_zh.py"
OUT_DICT = ROOT / "ps5/webui/src/js/00c-i18n-dict.js"
OUT_DOCS = ROOT / "ps5/webui/src/js/11b-docs-zh.js"


def js_string(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    ns = runpy.run_path(str(UI))
    zh = dict(ns["ZH"])
    # Drop anything that would rewrite a generation prompt or an API token.
    banned_prefixes = (
        "a lighthouse",
        "a red fox",
        "a cozy cabin",
        "a futuristic",
        "a astronaut",
        "a bowl of ramen",
        "a tiny robot",
        "a sailing ship",
        "an ancient temple",
    )
    for key in list(zh):
        low = key.lower()
        if low.startswith(banned_prefixes):
            raise SystemExit("dictionary must not translate a surprise prompt: " + key)
        if key != key.strip() and zh[key] == key:
            pass
    lines = ["  // Generated by scripts/emit-i18n.py. Edit ps5/webui/src/i18n/ui_zh.py."]
    lines.append("  ZH = {")
    for key in sorted(zh, key=lambda s: (s.lower(), s)):
        if not isinstance(zh[key], str) or zh[key] == "":
            raise SystemExit("empty translation: " + key)
        lines.append("    %s: %s," % (js_string(key), js_string(zh[key])))
    lines.append("  };")
    lines.append("")
    OUT_DICT.write_text("\n".join(lines), encoding="utf-8")

    def read(path):
        return (ROOT / path).read_text(encoding="utf-8")

    zh_docs = {
        "MODELS.md": read("docs/zh-CN/MODELS.md"),
        "API.md": read("docs/zh-CN/API.md"),
    }
    en_docs = {
        "MODELS.md": read("docs/MODELS.md"),
        "API.md": read("docs/API.md"),
    }
    doc_js = [
        "  // Generated by scripts/emit-i18n.py. Chinese Help text, plus the English",
        "  // docs used when docs/API.md is the web UI payload (PS5SD-UI-PAYLOAD).",
        "  var ZH_DOCS = {",
        "    'MODELS.md': %s," % js_string(zh_docs["MODELS.md"]),
        "    'API.md': %s" % js_string(zh_docs["API.md"]),
        "  };",
        "  var EN_DOCS = {",
        "    'MODELS.md': %s," % js_string(en_docs["MODELS.md"]),
        "    'API.md': %s" % js_string(en_docs["API.md"]),
        "  };",
        "",
    ]
    OUT_DOCS.write_text("\n".join(doc_js), encoding="utf-8")
    print("dict", len(zh), "bytes", OUT_DICT.stat().st_size)
    print("docs", OUT_DOCS.stat().st_size)


if __name__ == "__main__":
    main()
